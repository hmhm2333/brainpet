#!/usr/bin/env node

import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const targets = readJson("config/companion-target-profiles.json");
const lifecycle = readJson("config/brainpet-agent-lifecycle.json");
const distribution = readJson("config/brainpet-distribution.json");
const registry = readJson("config/brainpet-adapter-registry.json");

validateSources();

const outputs = new Map([
  ["packages/adapter-core/src/generated-contract.ts", renderAdapterCore()],
  ["packages/agent-events/src/generated-contract.ts", renderAgentEvents()],
  ["integrations/codex/plugins/brainpet-codex-bridge/scripts/generated-contract.mjs", renderNodeContract()],
  ["native/brainpet-hook/src/generated_contract.rs", renderRustContract()],
  ["apps/desktop/src/generated-brainpet-distribution.ts", renderDesktopDistribution()],
]);

export function assertBrainPetAdapterContractsCurrent() {
  for (const [path, expected] of outputs) {
    assert.equal(normalize(readFileSync(resolve(root, path), "utf8")), expected, `Generated adapter contract is stale: ${path}`);
  }
}

export function generateBrainPetAdapterContracts() {
  for (const [path, content] of outputs) writeFileSync(resolve(root, path), content, "utf8");
}

function validateSources() {
  assert.equal(targets.schemaVersion, 1);
  assert.equal(lifecycle.schemaVersion, 1);
  assert.equal(distribution.schemaVersion, 2);
  assert.equal(targets.adapterVersion, registry.adapterVersion);
  assert.deepEqual(targets.ipc, {
    protocol: "openpets-ipc",
    version: 1,
    maxMessageBytes: 16 * 1024,
    connectTimeoutMs: 2_000,
    responseTimeoutMs: 3_000,
  });
  assert.deepEqual(Object.keys(targets.products), ["brainpet", "openpets"]);
  assert.equal(targets.products.brainpet.appId, distribution.identity.appId);
  assert.equal(targets.products.brainpet.updateChannel, distribution.identity.updateRepository);
  assert.equal(lifecycle.ipcMethod, "agent.activity");
  assert.equal(lifecycle.deliveryDeadlineMs, 1_000);
  assert.deepEqual(lifecycle.states, ["working", "waiting", "ready", "blocked", "idle"]);
  assert.equal(distribution.bridge.minimumRuntimeIpcVersion, 1);
  assert.deepEqual(distribution.releasePolicy, {
    channel: "direct-download",
    platformSignatureStatus: "absent-by-policy",
    userConsentRequired: true,
    storeRegistrationRequired: false,
    publisherRegistrationRequired: false,
    provenance: "sigstore-keyless",
  });
}

function renderAdapterCore() {
  return normalize(`// Generated by scripts/generate-brainpet-adapter-contracts.mjs. Do not edit.\nexport const adapterContractVersion = ${JSON.stringify(targets.adapterVersion)} as const;\nexport const targetProductDefinitions = ${JSON.stringify(targets.products, null, 2)} as const;\n`);
}

function renderAgentEvents() {
  return normalize(`// Generated by scripts/generate-brainpet-adapter-contracts.mjs. Do not edit.\nexport const agentActivitySchemaVersion = ${lifecycle.schemaVersion} as const;\nexport const agentActivityMethod = ${JSON.stringify(lifecycle.ipcMethod)} as const;\nexport const agentActivityDeliveryDeadlineMs = ${lifecycle.deliveryDeadlineMs} as const;\nexport const normalizedAgentLifecycleStates = ${JSON.stringify(lifecycle.states)} as const;\nexport const agentActivityRequiredFields = ${JSON.stringify(lifecycle.requiredFields)} as const;\nexport const agentActivityOptionalFields = ${JSON.stringify(lifecycle.optionalFields)} as const;\nexport const agentActivityPrivacyRejectedFields = ${JSON.stringify(lifecycle.privacyRejectedFields)} as const;\nexport const companionIpcProtocol = ${JSON.stringify(targets.ipc.protocol)} as const;\nexport const companionIpcVersion = ${targets.ipc.version} as const;\nexport const companionIpcMaxMessageBytes = ${targets.ipc.maxMessageBytes} as const;\nexport const companionIpcConnectTimeoutMs = ${targets.ipc.connectTimeoutMs} as const;\nexport const companionIpcResponseTimeoutMs = ${targets.ipc.responseTimeoutMs} as const;\n`);
}

function renderNodeContract() {
  const bridge = distribution.bridge;
  return normalize(`// Generated by scripts/generate-brainpet-adapter-contracts.mjs. Do not edit.\nexport const adapterVersion = ${JSON.stringify(targets.adapterVersion)};\nexport const agentActivitySchemaVersion = ${lifecycle.schemaVersion};\nexport const agentActivityMethod = ${JSON.stringify(lifecycle.ipcMethod)};\nexport const lifecycleStates = Object.freeze(${JSON.stringify(lifecycle.states)});\nexport const privacyRejectedFields = Object.freeze(${JSON.stringify(lifecycle.privacyRejectedFields)});\nexport const ipcProtocol = ${JSON.stringify(targets.ipc.protocol)};\nexport const ipcProtocolVersion = ${targets.ipc.version};\nexport const maxIpcMessageBytes = ${targets.ipc.maxMessageBytes};\nexport const hookDeadlineMs = ${bridge.hookDeadlineMs};\nexport const connectAttemptMs = ${bridge.connectAttemptMs};\nexport const runtimePollIntervalMs = ${bridge.pollIntervalMs};\nexport const brainPetTarget = Object.freeze(${JSON.stringify(targets.products.brainpet, null, 2)});\n`);
}

function renderRustContract() {
  const bridge = distribution.bridge;
  return normalize(`// Generated by scripts/generate-brainpet-adapter-contracts.mjs. Do not edit.\npub const ADAPTER_VERSION: &str = ${rustString(targets.adapterVersion)};\npub const AGENT_ACTIVITY_SCHEMA_VERSION: u64 = ${lifecycle.schemaVersion};\npub const AGENT_ACTIVITY_METHOD: &str = ${rustString(lifecycle.ipcMethod)};\npub const LIFECYCLE_STATES: &[&str] = &[${lifecycle.states.map(rustString).join(", ")}];\npub const PRIVACY_REJECTED_FIELDS: &[&str] = &[\n    ${lifecycle.privacyRejectedFields.map(rustString).join(",\n    ")},\n];\npub const IPC_PROTOCOL: &str = ${rustString(targets.ipc.protocol)};\npub const IPC_PROTOCOL_VERSION: u64 = ${targets.ipc.version};\npub const MAX_IPC_MESSAGE_BYTES: usize = ${targets.ipc.maxMessageBytes};\npub const HOOK_DEADLINE_MS: u64 = ${bridge.hookDeadlineMs};\npub const CONNECT_ATTEMPT_MS: u64 = ${bridge.connectAttemptMs};\npub const RUNTIME_POLL_INTERVAL_MS: u64 = ${bridge.pollIntervalMs};\npub const BRAINPET_APP_ID: &str = ${rustString(targets.products.brainpet.appId)};\npub const BRAINPET_PRODUCT_DIRECTORY: &str = ${rustString(targets.products.brainpet.productDirectory)};\npub const BRAINPET_RUNTIME_NAMESPACE: &str = ${rustString(targets.products.brainpet.runtimeNamespace)};\n`);
}

function renderDesktopDistribution() {
  return normalize(`// Generated by scripts/generate-brainpet-adapter-contracts.mjs. Do not edit.\nexport const brainPetBridgeVersion = ${JSON.stringify(distribution.bridge.version)} as const;\nexport const brainPetReleaseTargets = ${JSON.stringify(distribution.releaseTargets, null, 2)} as const;\nexport const brainPetDistributionIdentity = ${JSON.stringify(distribution.identity, null, 2)} as const;\nexport const brainPetReleasePolicy = ${JSON.stringify(distribution.releasePolicy, null, 2)} as const;\n`);
}

function rustString(value) { return JSON.stringify(value); }
function normalize(value) { return value.replaceAll("\r\n", "\n").replace(/\n*$/, "\n"); }
function readJson(path) { return JSON.parse(readFileSync(resolve(root, path), "utf8")); }

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    assertBrainPetAdapterContractsCurrent();
    console.log("Generated BrainPet adapter contracts are current.");
  } else {
    generateBrainPetAdapterContracts();
    console.log(`Generated ${outputs.size} BrainPet adapter contract files.`);
  }
}
